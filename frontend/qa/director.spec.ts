 await page.setViewportSize({width,height:950});
 await page.addInitScript(()=>{(window as any).__directorFriction={clicks:0,fields:[],screens:[],started:performance.now()};document.addEventListener('click',()=>{(window as any).__directorFriction.clicks++;},true);document.addEventListener('input',event=>{const el=event.target as HTMLElement;const name=el.getAttribute('aria-label')||el.closest('label')?.textContent?.trim()||el.getAttribute('name')||el.tagName;const data=(window as any).__directorFriction;if(!data.fields.includes(name))data.fields.push(name);},true);addEventListener('hashchange',()=>{(window as any).__directorFriction.screens.push(location.hash.split('?')[0]);});});
