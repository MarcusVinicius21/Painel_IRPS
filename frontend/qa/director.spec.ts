 for(const fmt of ['DOCX','PDF']){
  await page.getByRole('button',{name:'Gerar '+fmt,exact:true}).click();
  await expect(page.getByRole('link',{name:new RegExp('Baixar IRPS_minuta_.*\\.'+fmt.toLowerCase())})).toBeVisible();
 }
