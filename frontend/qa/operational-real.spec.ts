import {test,expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';

test('piloto oficial: um acesso, histórico e IRP sem manifestações inventadas',async({page})=>{
 test.skip(process.env.IRPS_OPERATIONAL_REAL!=='1','Exige o banco operacional separado e consultas públicas já comprovadas.');
 test.setTimeout(180000);
 const root=path.resolve('..'),out=path.join(root,'docs/IRPS_PILOTO_REAL_LOGIN_UNICO/capturas');fs.mkdirSync(out,{recursive:true});
 const network:{path:string;status:number}[]=[];const errors:string[]=[];
 page.on('response',r=>{if(r.url().includes('/api/v1/'))network.push({path:new URL(r.url()).pathname,status:r.status()});});
 page.on('pageerror',e=>errors.push(e.message));
 const capture=async(name:string,fullPage=false)=>{const close=page.getByRole('button',{name:'Fechar mensagem',exact:true});if(await close.count())await close.click();await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:path.join(out,name),fullPage});};
 await page.setViewportSize({width:1672,height:941});await page.goto('/');
 await expect(page.getByLabel('Senha de acesso')).toBeVisible();
 await expect(page.getByText('Escolha uma conta de teste')).toHaveCount(0);
 const secret=JSON.parse(fs.readFileSync(path.join(root,'.runtime/operacional-local/acesso-privado.json'),'utf8'));
 await page.getByLabel('Senha de acesso').fill(secret.password);
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await expect(page.locator('.irps-shell')).toBeVisible();
 await expect(page.locator('.organization-switch')).toHaveCount(0);
 await expect(page.getByText('Operação local',{exact:true}).first()).toBeVisible();
 const cookie=(await page.context().cookies()).find(c=>c.name==='irps_operator_csrf')!;
 const get=async(p:string)=>{const r=await page.request.get('/api/v1'+p);expect(r.ok(),p).toBeTruthy();return r.json();};
 const post=async(p:string,body:unknown={})=>{const r=await page.request.post('/api/v1'+p,{data:body,headers:{'X-CSRF-Token':cookie.value}});expect(r.ok(),p+' '+r.status()+' '+(await r.text()).slice(0,250)).toBeTruthy();return r.json();};
 const identity=await get('/auth/context');expect(identity.identity_mode).toBe('operational_local');expect(identity.permissions).toContain('quote.write');
 for(const endpoint of ['/quotes','/documents','/scenarios','/director/studies','/audit'])await get(endpoint);
 expect((await page.request.get('/api/v1/auth/test-users')).status()).toBe(404);
 await page.getByRole('heading',{name:'Resumo das informações disponíveis'}).waitFor();
 await expect(page.getByText('Ipatinga/MG',{exact:false}).first()).toBeVisible({timeout:20000});
 await capture('01-inicio-1672.png');
 await page.goto('/#/inteligencia');
 const available=await get('/director/observed-items');
 const item=available.records.find((i:any)=>i.source_url.includes('/19876424000142/')&&!i.unit.toLocaleUpperCase('pt-BR').includes('SERVI'))||available.records.find((i:any)=>i.description.startsWith('PIA -'));
 expect(item).toBeTruthy();expect(item.source_url).toMatch(/^https:\/\/pncp.gov.br\//);
 const row=page.locator('.observed-item-list li[data-fact-id="'+item.id+'"]');
 await row.getByRole('button',{name:'Analisar este item'}).click();
 await expect(page.getByRole('button',{name:'Conferir histórico por município'})).toBeEnabled();
 const historyResponse=page.waitForResponse(r=>new URL(r.url()).pathname.match(/\/director\/history\/[\w-]+$/)!==null);
 await page.getByRole('button',{name:'Conferir histórico por município'}).click();
 const history=await (await historyResponse).json();
 expect(history.scope.phase).toBe('publicado_estimado');expect(history.summary.observed_quantity).not.toBeNull();
 expect(history.municipalities.some((m:any)=>m.municipality.ibge==='3131307'&&m.observed_records>0)).toBeTruthy();
 expect(history.municipalities.find((m:any)=>m.municipality.ibge==='3168705').observed_quantity).toBeNull();
 await expect(page.locator('.municipal-history-panel')).toBeVisible();
 await capture('02-historico-1672.png');
 await page.goto('/#/inteligencia?etapa=planejamento');
 await page.getByLabel('Documento ou referência da conferência técnica').fill('Identidade e unidade conferidas diretamente no item publicado: '+item.source_url+'. Sem validação de necessidade futura.');
 await page.getByText('Conferi a especificação e a unidade para este estudo.',{exact:true}).click();
 const created=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/v1/director/studies'&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Criar planejamento / Preparar IRP',exact:true}).click();
 const study=await (await created).json();expect(study.id).toBeTruthy();
 expect(study.scenario.snapshot.inputs).toEqual({});expect(study.payload.preliminary_target).toBeNull();
 await expect(page.getByRole('button',{name:'Preparar prévia da minuta'})).toBeVisible();
 const calculation=await post('/scenarios/'+study.scenario.id+'/calculate');
 const lines=await get('/calculations/'+calculation.id+'/lines');
 expect(lines.records.length).toBe(2);expect(lines.records.every((l:any)=>l.quantity===null)).toBeTruthy();
 const modeB=await post('/scenarios',{title:'Verificação operacional do modo B · sem meta aprovada',classification:'internal',snapshot:{...study.scenario.snapshot,mode:'B',allocations:{},inputs:{},prices:{},justification:'Sem quantidade global aprovada. Não distribuir os registros históricos.'}});
 const calculationB=await post('/scenarios/'+modeB.id+'/calculate');
 const linesB=await get('/calculations/'+calculationB.id+'/lines');
 expect(linesB.records.every((l:any)=>l.quantity===null&&l.state==='bloqueado')).toBeTruthy();
 await page.goto('/#/inteligencia?estudo='+study.id+'&etapa=planejamento');
 await expect(page.getByText('Dados insuficientes para cálculo',{exact:false}).first()).toBeVisible();
 await capture('03-planejamento-1672.png');
 await page.goto('/#/inteligencia?estudo='+study.id+'&etapa=preparacao');
 await page.getByLabel('Objeto da minuta').fill(item.description);
 await page.getByLabel('Evidência da conferência do objeto e dos itens').fill('Objeto e unidade reproduzem o mesmo item documentado: '+item.source_url+'. Não há confirmação de participação municipal.');
 await page.getByText('Conferi que objeto, especificação e unidade pertencem ao mesmo estudo.',{exact:true}).click();
 const drafted=page.waitForResponse(r=>new URL(r.url()).pathname.endsWith('/drafts')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Preparar prévia da minuta'}).click();
 const draft=await (await drafted).json();expect(draft.validation.state).toBe('needs_review');expect(draft.validation.officially_published).toBe(false);
 await expect(page.getByText('Minuta em revisão',{exact:true}).first()).toBeVisible();
 const exports=[];
 for(const format of ['docx','pdf']){
  const artifact=await post('/irp-drafts/'+draft.id+'/exports/'+format);const file=await page.request.get(artifact.download_url);
  expect(file.ok()).toBeTruthy();expect((await file.body()).length).toBeGreaterThan(500);exports.push({format,filename:artifact.filename,bytes:(await file.body()).length});
 }
 await capture('04-irp-1672.png');
 await page.goto('/#/inteligencia?estudo='+study.id+'&etapa=manifestacoes');
 await expect(page.getByRole('heading',{name:'Manifestações dos municípios',exact:true})).toBeVisible();
 const register=await get('/director/studies/'+study.id+'/register');
 expect(register.confirmed_known_total).toBeNull();expect(register.pending_municipalities).toBe(2);
 await capture('05-manifestacoes-1672.png');
 const invalid=await page.request.post('/api/v1/director/studies/'+study.id+'/operations',{headers:{'X-CSRF-Token':cookie.value},data:{kind:'manifestation',municipality_ibge:'3131307',expected_revision:0,scenario_revision:1,status:'confirmed',quantity:'1',note:'Não existem documentos para esta confirmação.'}});
 expect(invalid.status()).toBe(422);
 await page.goto('/#/inteligencia?estudo='+study.id+'&etapa=consolidacao');
 await expect(page.getByRole('heading',{name:'Consolidação por município e item'})).toBeVisible();
 expect((await get('/director/studies/'+study.id+'/register')).confirmed_known_total).toBeNull();
 await capture('06-consolidacao-1672.png');
 await page.setViewportSize({width:390,height:844});await capture('07-consolidacao-390.png',true);
 await page.goto('/#/inteligencia?estudo='+study.id+'&etapa=historico');
 await expect(page.locator('.municipal-history-panel')).toBeVisible();await expect(page.getByText('Dados insuficientes',{exact:true}).first()).toBeVisible();await capture('08-historico-390.png',true);
 expect(errors).toEqual([]);
 fs.writeFileSync(path.join(root,'docs/IRPS_PILOTO_REAL_LOGIN_UNICO/jornada-real.json'),JSON.stringify({study_id:study.id,scenario_id:study.scenario.id,draft_id:draft.id,mode_a:calculation.summary,mode_b:calculationB.summary,mode_b_scenario_id:modeB.id,source_url:item.source_url,original_item:item.description,history,register,exports,network,page_errors:errors,synthetic_data_used:false},null,2));
});

test('acesso operacional às áreas existentes sem seleção de contas fictícias',async({page})=>{
 test.skip(process.env.IRPS_OPERATIONAL_REAL!=='1','Somente ambiente operacional separado.');
 test.setTimeout(180000);
 const root=path.resolve('..');
 await page.goto('/');await page.getByLabel('Senha de acesso').fill(JSON.parse(fs.readFileSync(path.join(root,'.runtime/operacional-local/acesso-privado.json'),'utf8')).password);
 await page.getByRole('button',{name:'Entrar',exact:true}).click();await expect(page.locator('.irps-shell')).toBeVisible();
 const results=[];
 for(const route of ['inicio','inteligencia','oportunidades','catalogo-inteligente','pesquisa','comparar','necessidades','negocio','documentos','fontes','alertas','administracao','licitacao']){
  await page.goto('/#/'+route);await expect(page.getByRole('heading',{level:1})).toBeVisible();
  await expect(page.locator('option[value="synthetic"]')).toHaveCount(0);
  await expect(page.getByText('Escolha uma conta de teste')).toHaveCount(0);
  results.push({route,title:await page.getByRole('heading',{level:1}).innerText()});
 }
 await page.goto('/#/negocio');await expect(page.getByRole('button',{name:'Calcular e salvar simulação'})).toBeEnabled();
 fs.writeFileSync(path.join(root,'docs/IRPS_PILOTO_REAL_LOGIN_UNICO/modulos-acessiveis.json'),JSON.stringify(results,null,2));
});
